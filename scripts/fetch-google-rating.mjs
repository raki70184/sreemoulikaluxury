#!/usr/bin/env node
/**
 * Build-time fetch of the live Google rating + review count.
 *
 * Calls the Google Places API for the salon's place and writes the result to
 * src/data/googleRating.generated.ts, which GoogleRatingBadge.tsx imports. The
 * value is baked into the bundle at `vite build` and therefore lands in the
 * prerendered static HTML — so the visible badge and the AggregateRating JSON-LD
 * (both read the same constant) stay in sync and refresh on every deploy. No
 * more hand-editing a Netlify env var.
 *
 * Resilient by design: this script must NEVER fail the build. If the API key is
 * missing, the network call fails, or the API returns junk, it keeps the last
 * committed values (or writes a safe fallback if the file is missing) and exits 0.
 *
 * Required env (set in Netlify; optional locally via .env):
 *   GOOGLE_PLACES_API_KEY   server-side key with "Places API (New)" enabled
 *   GOOGLE_PLACE_ID         optional; defaults to the salon's known place id
 *
 *   node scripts/fetch-google-rating.mjs
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = dirname(__dirname);
const OUT_DIR = join(REPO_ROOT, "src", "data");
const OUT_FILE = join(OUT_DIR, "googleRating.generated.ts");

// The salon's Google place — public id, already present in the site schema.
const DEFAULT_PLACE_ID = "ChIJu3tkyN-byzsRDq93zKzDG2M";
// Last-resort values if no committed file exists AND the fetch can't run.
const HARD_FALLBACK = { rating: 4.9, count: 471 };
const FETCH_TIMEOUT_MS = 10000;

// --- optionally load .env for local runs (Netlify injects real env vars) -----
async function loadEnv() {
  const envFile = join(REPO_ROOT, ".env");
  if (!existsSync(envFile)) return;
  const text = await readFile(envFile, "utf8");
  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const idx = trimmed.indexOf("=");
    if (idx < 0) continue;
    const key = trimmed.slice(0, idx).trim();
    const val = trimmed.slice(idx + 1).trim();
    if (!process.env[key]) process.env[key] = val;
  }
}

function render({ rating, count }) {
  const stamp = new Date().toISOString().slice(0, 10);
  return `/**
 * AUTO-GENERATED by scripts/fetch-google-rating.mjs — do not edit by hand.
 *
 * Live Google rating + review count for the salon, refreshed at build time from
 * the Google Places API. The committed values below are the FALLBACK used when
 * the build-time fetch is unavailable (no API key, network/API error, or a plain
 * local build) so the rating badge + AggregateRating schema never break.
 *
 * GoogleRatingBadge.tsx reads these constants for BOTH the visible badge and the
 * JSON-LD, so the number a human sees and the number Google reads can never drift.
 *
 * Refresh manually with: \`npm run fetch:rating\` (needs GOOGLE_PLACES_API_KEY).
 */
export const GOOGLE_RATING = ${rating};
export const GOOGLE_REVIEW_COUNT = ${count};
export const GOOGLE_RATING_FETCHED_AT = ${JSON.stringify(stamp)};
`;
}

// Round to one decimal — Google ratings carry one decimal place.
function round1(n) {
  return Math.round(n * 10) / 10;
}

function valid(rating, count) {
  return (
    typeof rating === "number" &&
    !Number.isNaN(rating) &&
    rating >= 1 &&
    rating <= 5 &&
    Number.isInteger(count) &&
    count > 0
  );
}

async function ensureFileExists() {
  if (existsSync(OUT_FILE)) return;
  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT_FILE, render(HARD_FALLBACK));
  console.warn("[fetch-rating] no prior file — wrote hard fallback.");
}

async function run() {
  await loadEnv();
  const apiKey = process.env.GOOGLE_PLACES_API_KEY;
  const placeId = process.env.GOOGLE_PLACE_ID || DEFAULT_PLACE_ID;

  if (!apiKey) {
    console.warn("[fetch-rating] GOOGLE_PLACES_API_KEY not set — keeping committed values.");
    await ensureFileExists();
    return;
  }

  const url = `https://places.googleapis.com/v1/places/${encodeURIComponent(placeId)}`;
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), FETCH_TIMEOUT_MS);
  let data;
  try {
    const res = await fetch(url, {
      headers: {
        "X-Goog-Api-Key": apiKey,
        "X-Goog-FieldMask": "rating,userRatingCount",
      },
      signal: ctrl.signal,
    });
    if (!res.ok) {
      const body = await res.text().catch(() => "");
      throw new Error(`Places API ${res.status}: ${body.slice(0, 200)}`);
    }
    data = await res.json();
  } finally {
    clearTimeout(timer);
  }

  // New Places API: { rating, userRatingCount }. Tolerate the legacy shape too.
  const rating = round1(Number(data.rating ?? data.result?.rating));
  const count = Number(data.userRatingCount ?? data.result?.user_ratings_total);
  if (!valid(rating, count)) {
    throw new Error(`unexpected payload: ${JSON.stringify(data).slice(0, 200)}`);
  }

  await mkdir(OUT_DIR, { recursive: true });
  await writeFile(OUT_FILE, render({ rating, count }));
  console.log(`[fetch-rating] updated -> ${rating} stars / ${count} reviews`);
}

// Top-level guard: a failed fetch must never break the build.
try {
  await run();
} catch (err) {
  console.warn(`[fetch-rating] ${err.message} — keeping committed values.`);
  try {
    await ensureFileExists();
  } catch {
    /* nothing more we can safely do */
  }
}
